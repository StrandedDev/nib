//! Single registry of user actions. The keymap and the command palette both read from it;
//! config overrides remap by `config_key`.

#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum CommandId {
    Palette,
    Save,
    SaveAs,
    Open,
    Quit,
    Find,
    FindNext,
    FindPrev,
    Replace,
    GotoLine,
    Undo,
    Redo,
    Copy,
    Cut,
    Paste,
    SelectAll,
    ToggleWrap,
    ToggleLineNumbers,
    Left,
    Right,
    Up,
    Down,
    WordLeft,
    WordRight,
    Home,
    End,
    PageUp,
    PageDown,
    FileStart,
    FileEnd,
    SelLeft,
    SelRight,
    SelUp,
    SelDown,
    SelWordLeft,
    SelWordRight,
    SelHome,
    SelEnd,
    Backspace,
    Delete,
    DeleteWordBack,
    DeleteWordFwd,
    Newline,
    Tab,
}

pub struct CommandInfo {
    pub id: CommandId,
    /// Human label shown in the palette.
    pub name: &'static str,
    /// Snake_case key used by the config file.
    pub config_key: &'static str,
    /// Default chords, in display order; shown by `Keymap::keys_for`.
    pub default_keys: &'static [&'static str],
    /// Default chords that are bound but hidden from `keys_for` (e.g. F1 for the palette).
    pub hidden_keys: &'static [&'static str],
    pub in_palette: bool,
}

